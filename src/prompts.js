/** 组装开始节点 xuqiu：合同类型 / 审查立场 / 重点审查 / 补充要求 */
function buildXuqiu(payload) {
  const parts = [];
  parts.push(`合同类型：${payload.contractType || '未指定'}`);
  parts.push(`审查立场：${payload.stance || '中立'}`);
  const focuses = Array.isArray(payload.focuses) ? payload.focuses.filter(Boolean) : [];
  parts.push(`重点审查内容：${focuses.length ? focuses.join('、') : '按通用条款全面审查'}`);
  if (payload.extra && payload.extra.trim()) parts.push(`补充审查要求：${payload.extra.trim()}`);
  return parts.join('\n');
}

function fill(template, vars) {
  return Object.keys(vars).reduce(
    (acc, key) => acc.split(`{{${key}}}`).join(vars[key] == null ? '' : vars[key]),
    template
  );
}

